def test_python_covariance_kernels_match_closed_form_values():
    sq_dist = build_sq_dist_mat.py_func(3)
    abs_dist = build_abs_dist_mat.py_func(3)
    expected_dist = np.array([[0.0, 0.5, 1.0], [0.5, 0.0, 0.5], [1.0, 0.5, 0.0]])
    np.testing.assert_allclose(abs_dist, expected_dist)
    np.testing.assert_allclose(sq_dist, expected_dist**2)

    linear = get_linear_kernel.py_func(3, np.array([2.0]))
    rbf = get_rbf_kernel.py_func(3, np.array([0.5]), np.array([2.0]))
    periodic = get_periodic_kernel.py_func(
        3,
        np.array([0.5]),
        np.array([1.0]),
        np.array([2.0]),
    )

    np.testing.assert_allclose(linear[0], 2.0 * np.outer([0.0, 0.5, 1.0], [0.0, 0.5, 1.0]))
    np.testing.assert_allclose(np.diag(rbf[0]), 4.0)
    np.testing.assert_allclose(np.diag(periodic[0]), 4.0)
    np.testing.assert_allclose(periodic[0, 0, 2], 4.0)


def test_python_gaussian_process_rollout_returns_finite_bounded_values():
    result = sample_gaussian_process.py_func(
        local_params=np.empty((2, 3)),
        start=np.array([0.0, 1.0]),
        kernel_mat=np.broadcast_to(np.eye(3), (2, 3, 3)),
        bounds=np.array([-2.0, 3.0]),
        noise=1e-9,
    )

    assert result.shape == (2, 3)
    assert np.all(np.isfinite(result))
    assert np.all((-2.0 < result) & (result < 3.0))
