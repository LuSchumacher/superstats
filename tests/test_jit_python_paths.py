"""Tests for the Python implementations wrapped by Numba dispatchers.

The public, compiled call paths are covered elsewhere. Exercising ``py_func``
here both checks the underlying algorithms directly and keeps their branches
visible to coverage.py, which cannot trace machine code generated by Numba.
"""

import numpy as np

from superstats.simulation.cognitive.cdm import sample_cdm
from superstats.simulation.cognitive.ddm import sample_ddm
from superstats.simulation.cognitive.rdm import sample_rdm
from superstats.transition.stochastic.auto_regression import _one_step_ar1, _sample_ar1
from superstats.transition.stochastic.gaussian_process import sample_gaussian_process
from superstats.transition.stochastic.jump import _one_step_jump, _sample_jump_process
from superstats.transition.stochastic.kernel.linear import get_linear_kernel
from superstats.transition.stochastic.kernel.periodic import build_abs_dist_mat, get_periodic_kernel
from superstats.transition.stochastic.kernel.rbf import build_sq_dist_mat, get_rbf_kernel
from superstats.transition.stochastic.levy_flight import (
    _one_step_levy_flight,
    _sample_alpha_stable,
    _sample_levy_flight,
)
from superstats.transition.stochastic.ornstein_uhlenbeck import _one_step_ou, _sample_ou
from superstats.transition.stochastic.random_walk import _one_step_random_walk, _sample_random_walk


def sigmoid(values):
    return 1.0 / (1.0 + np.exp(-np.asarray(values)))


def test_python_ddm_covers_both_boundaries_and_timeout():
    result = sample_ddm.py_func(
        v=np.array([2.0, -2.0, 0.0]),
        a=np.array([1.0, 1.0, 1e6]),
        tau=np.array([0.1, 0.2, 0.3]),
        bias=np.full(3, 0.5),
        sigma=0.0,
        dt=1.0,
        max_steps=1,
    )

    np.testing.assert_array_equal(result["choice"], [1.0, 0.0, -1.0])
    np.testing.assert_allclose(result["response_time"], [1.1, 1.2, -1.0])


def test_python_cdm_covers_crossing_and_timeout():
    result = sample_cdm.py_func(
        v_angle=np.array([np.pi / 2, 0.0]),
        v_length=np.array([2.0, 0.0]),
        a=np.array([1.0, 1e6]),
        tau=np.array([0.25, 0.0]),
        sigma=0.0,
        dt=1.0,
        max_steps=1,
    )

    np.testing.assert_allclose(result["response_time"], [1.25, -5.0])
    np.testing.assert_allclose(result["choice"], [np.pi / 2, -5.0])


